import { expect, test } from "@playwright/test";
import { encode } from "@auth/core/jwt";
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { localBase, localStatePath, type MobileLocalState } from "./mobile-local";
import { captureFixture, fixturePng, fixtureTaskState, guardFixtureAction, readManifest } from "./mobile-owned-fixtures";

for (const role of ["worker", "mounter"] as const) {
  test(`owned ${role}: touch scroll, photo and status-only completion`, async ({ page }, testInfo) => {
    test.skip(process.env.CRM_E2E_OWNED !== "1", "Только явно разрешённые project/task из локального UUID manifest");
    test.skip(testInfo.project.name !== (role === "worker" ? "mobile-360" : "mobile-390"), "Роль проверяется на назначенном мобильном viewport");
    expect(process.env.CRM_E2E_BASE_URL ?? localBase).toBe(localBase);
    const manifest = await guardFixtureAction(role);
    const owned = manifest.tasks[role];
    const state = JSON.parse(await readFile(localStatePath, "utf8")) as MobileLocalState;
    const profile = state.profiles[role]!;
    expect(profile.id).toBe(owned.userId);
    const cookie = await encode({ token: { id: profile.id, roles: profile.roles, sessionVersion: profile.sessionVersion }, secret: state.secret, salt: "authjs.session-token", maxAge: 1800 });
    await page.context().addCookies([{ name: "authjs.session-token", value: cookie, domain: "localhost", path: "/", httpOnly: true, secure: false, sameSite: "Lax" }]);
    await page.goto("/my");
    await page.getByRole("button", { name: "Канбан", exact: true }).click();
    const board = page.locator("[data-slot=kanban-scroll]");
    const card = board.locator("[data-slot=card]").filter({ hasText: owned.title }).first();
    await expect(card).toBeVisible();
    expect((await fixtureTaskState(role)).task.status).toBe("NEW");
    const handle = board.getByRole("button", { name: `Перетащить ${owned.title}`, exact: true });
    await expect(handle).toBeVisible();
    expect(await handle.evaluate((el) => getComputedStyle(el).touchAction)).toBe("none");
    expect(await card.evaluate((el) => getComputedStyle(el).touchAction)).not.toBe("none");
    const box = await card.boundingBox();
    const touch = await page.context().newCDPSession(page);
    const x = Math.min(page.viewportSize()!.width - 55, box!.x + box!.width - 55);
    const y = Math.min(page.viewportSize()!.height - 120, box!.y + 90);
    await touch.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x, y }] });
    for (let step = 1; step <= 8; step++) await touch.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: x - step * 20, y }] });
    await touch.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
    await expect.poll(() => board.evaluate((el) => el.scrollLeft)).toBeGreaterThan(40);
    expect((await fixtureTaskState(role)).task.status).toBe("NEW");
    await board.evaluate((el) => { el.scrollLeft = 0; });
    await page.screenshot({ path: testInfo.outputPath(`${role}-kanban.png`), animations: "disabled" });
    // Ручка запускает drag; отпускание в той же колонке не меняет статус.
    await handle.scrollIntoViewIfNeeded();
    const handleBox = await handle.boundingBox();
    await page.mouse.move(handleBox!.x + handleBox!.width / 2, handleBox!.y + handleBox!.height / 2);
    await page.mouse.down();
    await page.mouse.move(handleBox!.x - 25, handleBox!.y + 40, { steps: 5 });
    await expect(page.locator(".opacity-40").filter({ hasText: owned.title })).toBeVisible();
    await page.mouse.up();
    expect((await fixtureTaskState(role)).task.status).toBe("NEW");
    await card.getByRole("button", { name: "Фото", exact: true }).click();
    const dialog = page.getByRole("dialog");
    await expect(dialog.getByRole("button", { name: "Снять фото", exact: true })).toBeVisible();
    await expect(dialog.locator('input[type=file][capture=environment]')).toHaveAttribute("accept", "image/*");
    await page.screenshot({ path: testInfo.outputPath(`${role}-photo-dialog.png`), animations: "disabled" });
    const fileChooser = page.waitForEvent("filechooser");
    await dialog.getByRole("button", { name: "Выбрать файл", exact: true }).click();
    const responsePromise = page.waitForResponse((response) => response.url().endsWith("/api/files/upload") && response.request().method() === "POST");
    await (await fileChooser).setFiles(await fixturePng(role));
    const uploaded = await responsePromise;
    expect(uploaded.status()).toBe(200);
    expect((await uploaded.json()).ok).toBe(true);
    await expect(dialog).toBeHidden();
    await expect(card.getByRole("button", { name: "Фото (1)", exact: true })).toBeVisible();
    await captureFixture();
    await guardFixtureAction(role);
    await card.getByRole("button", { name: "Взять в работу", exact: true }).click();
    await expect.poll(async () => (await fixtureTaskState(role)).task.status).toBe("IN_PROGRESS");
    await expect(card.getByRole("button", { name: /^Стоп/ })).toHaveCount(0);
    const started = await fixtureTaskState(role);
    expect(started.time).toHaveLength(0);
    await card.scrollIntoViewIfNeeded();
    await page.screenshot({ path: testInfo.outputPath(`${role}-in-progress.png`), animations: "disabled" });
    await captureFixture();
    await guardFixtureAction(role);
    await card.getByRole("button", { name: "Завершить", exact: true }).click();
    await expect.poll(async () => (await fixtureTaskState(role)).task.status).toBe("DONE");
    const done = await fixtureTaskState(role);
    expect(done.task.doneAt).not.toBeNull();
    expect(done.time).toHaveLength(0);
    expect(done.payroll).toBe(0);
    await captureFixture();
    await expect(card.getByText("Выполнена", { exact: true })).toBeVisible();
    await card.scrollIntoViewIfNeeded();
    await page.screenshot({ path: testInfo.outputPath(`${role}-done.png`), animations: "disabled" });
  });

  test(`owned ${role}: completed receipt and local photo download`, async ({ page }, testInfo) => {
    test.skip(process.env.CRM_E2E_OWNED !== "1", "Только явно разрешённый UUID manifest");
    test.skip(testInfo.project.name !== (role === "worker" ? "mobile-360" : "mobile-390"), "Назначенный мобильный viewport");
    const manifest = await guardFixtureAction(role);
    const owned = manifest.tasks[role];
    const state = JSON.parse(await readFile(localStatePath, "utf8")) as MobileLocalState;
    const profile = state.profiles[role]!;
    const cookie = await encode({ token: { id: profile.id, roles: profile.roles, sessionVersion: profile.sessionVersion }, secret: state.secret, salt: "authjs.session-token", maxAge: 1800 });
    await page.context().addCookies([{ name: "authjs.session-token", value: cookie, domain: "localhost", path: "/", httpOnly: true, secure: false, sameSite: "Lax" }]);
    expect((await fixtureTaskState(role)).task.status).toBe("DONE");
    const file = (await readManifest()).files.find((file) => file.taskId === owned.id)!;
    expect(file).toBeTruthy();
    const response = await page.request.get(`/api/files/${file.id}`);
    expect(response.status()).toBe(200);
    expect(response.headers()["content-type"]).toContain("image/png");
    const expected = await fixturePng(role);
    expect(createHash("sha256").update(await response.body()).digest("hex"))
      .toBe(createHash("sha256").update(expected.buffer).digest("hex"));
    await page.goto("/my");
    const card = page.locator("[data-slot=kanban-scroll] [data-slot=card]").filter({ hasText: owned.title }).first();
    await expect(card.getByText("Выполнена", { exact: true })).toBeVisible();
    await card.scrollIntoViewIfNeeded();
    await page.screenshot({ path: testInfo.outputPath(`${role}-completed-receipt.png`), animations: "disabled" });
  });
}
